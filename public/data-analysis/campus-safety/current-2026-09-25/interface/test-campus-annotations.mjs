import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {parseFragment} from 'parse5';
import {addCampusAbbreviations} from '../src/lib/campus-abbreviations.js';
import {campusTerms,termMarkup,fullTerms} from '../src/lib/campus-terms.js';

const data=JSON.parse(readFileSync('public/data-analysis/campus-safety/data/dataset.json','utf8'));
const dictionary=campusTerms(data.institutions);
const text=node=>node.nodeName==='#text'?node.value:(node.childNodes??[]).map(text).join('');
const plain=html=>text(parseFragment(html));
const seen=new Set();
assert.equal(plain(termMarkup('IPEDS, then IPEDS.',dictionary,seen)), 'Integrated Postsecondary Education Data System (IPEDS), then IPEDS.');
assert.equal(plain(termMarkup('University of California, then UC and UCs.',dictionary,new Set())), 'University of California (UC), then UC and UCs.');
assert.equal(plain(termMarkup('ASRs; ASR.',dictionary,new Set())), 'annual security reports (ASRs); ASR.');
assert.equal(fullTerms('MIT / UCSD / VAWA',dictionary),'Massachusetts Institute of Technology / University of California, San Diego / Violence Against Women Act');
assert.equal(plain(termMarkup('NCEF Pediatric Dental Center',dictionary,new Set(),{verbatim:true})),'NCEF Pediatric Dental Center');
assert.equal(plain(termMarkup('University of California, San Diego. 2025 Annual Security Report.',dictionary,new Set(),{verbatim:true})),'University of California, San Diego. 2025 Annual Security Report.');
assert(!termMarkup('MIT',dictionary,new Set(),{interactive:true}).includes('tabindex'));
assert(termMarkup('<img src=x onerror="alert(1)"> IPEDS',dictionary,new Set()).startsWith('&lt;img'));
const formula='<math xmlns="http://www.w3.org/1998/Math/MathML"><mi>UC</mi></math>';
const script='<script type="application/json">{"name":"MIT","count":17}</script>';
const html=addCampusAbbreviations(`<div><select><option>MIT</option></select><p>MIT and MIT</p>${formula}${script}<p data-campus-no-terms>Pennsylvania</p><a href="/IPEDS/" id="source">IPEDS</a></div>`,data.institutions);
assert(html.includes('<option>Massachusetts Institute of Technology</option>'));
assert(html.includes('Massachusetts Institute of Technology (<abbr'),'Hidden options do not consume first use');
assert(html.includes(formula));assert(html.includes(script));
assert(html.includes('<p data-campus-no-terms="">Pennsylvania</p>'));
assert(html.includes('href="/IPEDS/" id="source"'),'Source anchors preserved');
const built=readFileSync('dist/writing/data-analysis/campus-safety/index.html','utf8');
assert(built.includes('Violence Against Women Act ('),'First use written out in static HTML');
assert(built.includes('data-definition="Integrated Postsecondary Education Data System"'));
assert(built.includes('role="doc-endnotes"'));
assert.equal((built.match(/<math[\s>]/g)||[]).length,7);
console.log('Campus annotations: first use, plural forms, native options, formal source titles, escaping, links and equations pass.');
